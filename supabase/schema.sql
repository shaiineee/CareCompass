-- Run once in your own Supabase SQL editor.
-- Creates all tables needed by CareCompass: the cloud-backup table, the team tasks table,
-- and the normalized user/events/checkins/alerts tables for future structured queries.
-- All tables use Row Level Security and grant access only to the service_role key
-- (the local Express server). No browser/anon access is allowed.

-- ─── Users ───
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null
);

-- ─── Team care tasks ───
-- Used by lib/services.js: teamTasks(), syncTaskCompletion(), checkSupabase().
-- The code queries WHERE user_id = 1, so insert at least one row into users first
-- (the seed insert below creates user id = 1 automatically).
create table if not exists public.tasks (
  id bigint generated always as identity primary key,
  user_id bigint not null default 1 references public.users(id),
  title text not null,
  instructions text,
  time text,
  note text,
  done boolean not null default false,
  status text not null default '',
  created_at timestamptz not null default now()
);

-- ─── Events (reminders, appointments, check-in schedules) ───
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id),
  title text,
  type text,
  date date,
  time text,
  note text
);

-- ─── Check-ins ───
create table if not exists public.checkins (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id),
  date timestamptz default now(),
  answers jsonb
);

-- ─── Alerts (caregiver updates) ───
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id),
  date timestamptz default now(),
  message text
);

-- ─── Full-record cloud backup ───
-- Used by lib/cloud.js: backupOne(), restoreOne(), cloudReady().
-- Stores the entire user session as a single JSONB blob.
create table if not exists public.carecompass_profiles (
  id uuid primary key,
  data jsonb not null,
  updated_at timestamptz not null default now()
);

-- ─── Security: Row Level Security on every table ───
alter table public.users               enable row level security;
alter table public.tasks               enable row level security;
alter table public.events              enable row level security;
alter table public.checkins            enable row level security;
alter table public.alerts              enable row level security;
alter table public.carecompass_profiles enable row level security;

-- Block anon and authenticated roles; only the service_role key can read/write.
revoke all on public.users               from anon, authenticated;
revoke all on public.tasks               from anon, authenticated;
revoke all on public.events              from anon, authenticated;
revoke all on public.checkins            from anon, authenticated;
revoke all on public.alerts              from anon, authenticated;
revoke all on public.carecompass_profiles from anon, authenticated;

grant select, insert, update, delete on public.users               to service_role;
grant select, insert, update, delete on public.tasks               to service_role;
grant select, insert, update, delete on public.events              to service_role;
grant select, insert, update, delete on public.checkins            to service_role;
grant select, insert, update, delete on public.alerts              to service_role;
grant select, insert, update, delete on public.carecompass_profiles to service_role;

-- Grant sequence usage for identity columns (needed for inserts into tables with generated IDs)
grant usage, select on all sequences in schema public to service_role;

-- ─── Seed: ensure user id = 1 exists so the tasks FK and hardcoded queries work ───
insert into public.users (id, name)
values (1, 'Default CareCompass User')
on conflict (id) do nothing;

-- ─── Ensure all expected columns exist (safe if table was created by an earlier run) ───
alter table public.tasks add column if not exists instructions text;
alter table public.tasks add column if not exists note text;
alter table public.tasks add column if not exists status text not null default '';
alter table public.tasks add column if not exists done boolean not null default false;
alter table public.tasks add column if not exists created_at timestamptz not null default now();

